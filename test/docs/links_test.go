// Package docs_test keeps the repository's prose documentation honest.
//
// Two things drift silently after a docs rewrite: a relative link that points
// at a file (or a heading) that no longer exists, and a documented
// ACKN4TH_* environment variable that the code never reads. Both are checked
// against the checkout only — no network, no wall clock — so the checks run
// anywhere.
package docs_test

import (
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"testing"
)

// skipTopLevel are directories at the repository root that are not part of the
// published documentation: scratch and review material, runtime state, and
// directories the sandbox may not even let us read.
var skipTopLevel = map[string]bool{
	".git": true, ".idea": true, "data": true, "config": true, "reviews": true,
}

var (
	linkRE       = regexp.MustCompile(`\[[^\]]*\]\(([^)\s]+)\)`)
	fenceRE      = regexp.MustCompile("(?ms)^```.*?^```")
	inlineRE     = regexp.MustCompile("`[^`\n]*`")
	headingRE    = regexp.MustCompile(`^(#{1,6})\s+(.*)$`)
	envRE        = regexp.MustCompile(`\bACKN4TH_[A-Z0-9_]+\b`)
	anchorSlugRE = regexp.MustCompile(`^[a-z0-9][a-z0-9-]*$`)
)

func repoRoot(t *testing.T) string {
	t.Helper()
	root, err := filepath.Abs("../..")
	if err != nil {
		t.Fatalf("repo root: %v", err)
	}
	if _, err := os.Stat(filepath.Join(root, "README.md")); err != nil {
		t.Fatalf("repo root %s has no README.md: %v", root, err)
	}
	return root
}

// markdownFiles lists every Markdown file that ships with the project.
func markdownFiles(t *testing.T, root string) []string {
	t.Helper()
	var files []string
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			// An unreadable directory (the runtime data/config dirs) holds no
			// documentation; nothing to check there.
			if d != nil && d.IsDir() {
				return fs.SkipDir
			}
			return nil
		}
		if d.IsDir() {
			if path != root && skipTopLevel[d.Name()] && filepath.Dir(path) == root {
				return fs.SkipDir
			}
			return nil
		}
		if strings.HasSuffix(path, ".md") {
			files = append(files, path)
		}
		return nil
	})
	if err != nil {
		t.Fatalf("walk: %v", err)
	}
	sort.Strings(files)
	if len(files) < 10 {
		t.Fatalf("only %d Markdown files found; the walk is not seeing the tree", len(files))
	}
	return files
}

// prose returns a Markdown file with code fences and inline code removed, so
// shell snippets that happen to contain brackets are not read as links.
func prose(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v", path, err)
	}
	s := fenceRE.ReplaceAllString(string(b), "")
	return inlineRE.ReplaceAllString(s, "")
}

// slugs returns the GitHub-style anchors a file's headings define.
func slugs(t *testing.T, path string) map[string]bool {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		return nil
	}
	out := map[string]bool{}
	for _, line := range strings.Split(fenceRE.ReplaceAllString(string(b), ""), "\n") {
		m := headingRE.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		text := strings.TrimSpace(strings.TrimRight(strings.TrimSpace(m[2]), "#"))
		text = inlineRE.ReplaceAllString(text, "")
		var b strings.Builder
		for _, r := range strings.ToLower(text) {
			switch {
			case r >= 'a' && r <= 'z', r >= '0' && r <= '9':
				b.WriteRune(r)
			case r == ' ' || r == '-':
				b.WriteRune('-')
			}
		}
		out[strings.Trim(b.String(), "-")] = true
	}
	return out
}

func TestRelativeLinksResolve(t *testing.T) {
	root := repoRoot(t)
	files := markdownFiles(t, root)
	links, anchors := 0, 0
	for _, file := range files {
		for _, m := range linkRE.FindAllStringSubmatch(prose(t, file), -1) {
			target := m[1]
			links++
			if strings.Contains(target, "://") || strings.HasPrefix(target, "mailto:") {
				continue
			}
			// Prose uses "[generated by …](…)" to mean "a link here", with the
			// ellipsis standing in for the target. That is not a link, and it
			// has no file to resolve.
			if strings.Trim(target, "…. ") == "" {
				continue
			}
			path, anchor, _ := strings.Cut(target, "#")
			path = strings.TrimPrefix(path, "./")
			dest := file
			if path != "" {
				dest = filepath.Join(filepath.Dir(file), path)
			}
			if _, err := os.Stat(dest); err != nil {
				rel, _ := filepath.Rel(root, file)
				relDest, _ := filepath.Rel(root, dest)
				t.Errorf("%s links to %s, which does not exist", rel, relDest)
				continue
			}
			if anchor == "" || !anchorSlugRE.MatchString(anchor) || !strings.HasSuffix(dest, ".md") {
				continue
			}
			anchors++
			if !slugs(t, dest)[anchor] {
				rel, _ := filepath.Rel(root, file)
				relDest, _ := filepath.Rel(root, dest)
				t.Errorf("%s links to %s#%s, but %s has no such heading", rel, relDest, anchor, relDest)
			}
		}
	}
	t.Logf("checked %d links (%d with anchors) in %d Markdown files", links, anchors, len(files))
	if links < 50 || anchors < 3 {
		t.Fatalf("only %d links and %d anchors found; the scan is not reading the prose", links, anchors)
	}
}

// TestDocumentedEnvVarsExist fails when the docs tell a reader to set a
// variable the binary never reads: the remote mode in the README is chosen by
// environment, so a stale name there is the difference between working and
// not working for a reader who follows the page.
func TestDocumentedEnvVarsExist(t *testing.T) {
	root := repoRoot(t)
	documented := map[string][]string{} // var -> files that document it
	for _, file := range markdownFiles(t, root) {
		if strings.HasPrefix(filepath.ToSlash(file), filepath.ToSlash(filepath.Join(root, "docs/qa"))) {
			continue // QA's own notes quote variables as history, not instructions
		}
		rel, _ := filepath.Rel(root, file)
		raw, err := os.ReadFile(file)
		if err != nil {
			t.Fatalf("read %s: %v", rel, err)
		}
		// Variables are documented inside code blocks, so scan raw text here.
		for _, v := range envRE.FindAllString(string(raw), -1) {
			documented[v] = append(documented[v], rel)
		}
	}
	if len(documented) == 0 {
		t.Fatal("no ACKN4TH_* variables found in the docs at all")
	}
	source := sourceText(t, root)
	t.Logf("checked %d ACKN4TH_* variables against the sources", len(documented))
	for v, files := range documented {
		if !strings.Contains(source, v) {
			t.Errorf("%s documents %s, but no Go source reads or names it", files[0], v)
		}
	}
}

// sourceText concatenates the project's Go sources, which is enough to tell
// whether a documented name exists anywhere in the code.
func sourceText(t *testing.T, root string) string {
	t.Helper()
	var b strings.Builder
	for _, dir := range []string{"cmd", "internal"} {
		err := filepath.WalkDir(filepath.Join(root, dir), func(path string, d fs.DirEntry, err error) error {
			if err != nil || d.IsDir() || !strings.HasSuffix(path, ".go") {
				return nil
			}
			bs, err := os.ReadFile(path)
			if err != nil {
				return nil
			}
			b.Write(bs)
			return nil
		})
		if err != nil {
			t.Fatalf("walk %s: %v", dir, err)
		}
	}
	if b.Len() == 0 {
		t.Fatal("no Go sources read")
	}
	return b.String()
}
